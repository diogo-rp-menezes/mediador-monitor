CREATE TABLE configuracoes_smtp_escritorio (
  escritorio_id integer PRIMARY KEY REFERENCES escritorios(id) ON DELETE RESTRICT,
  ativo boolean NOT NULL DEFAULT false,
  host text NOT NULL DEFAULT '',
  porta integer NOT NULL DEFAULT 587 CHECK (porta BETWEEN 1 AND 65535),
  secure boolean NOT NULL DEFAULT false,
  usuario text NOT NULL DEFAULT '',
  remetente text NOT NULL DEFAULT '',
  senha_cifrada text NOT NULL DEFAULT '',
  versao integer NOT NULL DEFAULT 1 CHECK (versao > 0),
  atualizado_em timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE clientes_documentos (
  cliente_id integer NOT NULL REFERENCES clientes(id) ON DELETE RESTRICT,
  numero_registro text NOT NULL REFERENCES registros(numero_registro) ON DELETE RESTRICT,
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'candidato' CHECK (status IN ('candidato','confirmado','rejeitado')),
  motivo text NOT NULL,
  contexto_hash text NOT NULL,
  origem text NOT NULL DEFAULT 'regra',
  incluir_envio boolean NOT NULL DEFAULT false,
  responsavel text,
  justificativa text,
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY(cliente_id, numero_registro),
  FOREIGN KEY(cliente_id, escritorio_id) REFERENCES clientes(id, escritorio_id) ON DELETE RESTRICT
);

CREATE INDEX clientes_documentos_escritorio_idx ON clientes_documentos(escritorio_id, cliente_id, status);

CREATE TABLE auditoria_clientes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  entidade text NOT NULL,
  entidade_id text NOT NULL,
  acao text NOT NULL,
  detalhes_json jsonb NOT NULL,
  criado_em timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX auditoria_clientes_escritorio_idx ON auditoria_clientes(escritorio_id, id DESC);

CREATE TABLE envios_clientes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  cliente_id integer NOT NULL,
  contato_id integer NOT NULL,
  numero_registro text NOT NULL REFERENCES registros(numero_registro) ON DELETE RESTRICT,
  versao text NOT NULL,
  status text NOT NULL CHECK (status IN ('bloqueado','preparando','revisao','na_fila','enviando','enviado','falhou','cancelado','incerto')),
  motivo text,
  snapshot_json jsonb,
  aprovado_por text,
  aprovado_em timestamptz,
  contexto_aprovacao text,
  tentativas integer NOT NULL DEFAULT 0 CHECK (tentativas >= 0),
  proxima_tentativa timestamptz,
  erro text,
  message_id text,
  resposta_smtp text,
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  enviado_em timestamptz,
  UNIQUE(cliente_id, contato_id, numero_registro, versao),
  UNIQUE(id, escritorio_id),
  FOREIGN KEY(cliente_id, escritorio_id) REFERENCES clientes(id, escritorio_id) ON DELETE RESTRICT,
  FOREIGN KEY(contato_id, escritorio_id) REFERENCES contatos(id, escritorio_id) ON DELETE RESTRICT
);

CREATE INDEX envios_status_idx ON envios_clientes(status, proxima_tentativa);
CREATE INDEX envios_escritorio_fila_idx ON envios_clientes(escritorio_id, status, proxima_tentativa, id);

CREATE TABLE tentativas_envio (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  envio_id bigint NOT NULL,
  escritorio_id integer NOT NULL,
  resultado text NOT NULL,
  erro text,
  message_id text,
  criado_em timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY(envio_id, escritorio_id) REFERENCES envios_clientes(id, escritorio_id) ON DELETE RESTRICT
);

CREATE INDEX tentativas_envio_escritorio_idx ON tentativas_envio(escritorio_id, envio_id, id);

CREATE FUNCTION impedir_transferencia_envio() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.escritorio_id IS DISTINCT FROM OLD.escritorio_id
     OR NEW.cliente_id IS DISTINCT FROM OLD.cliente_id
     OR NEW.contato_id IS DISTINCT FROM OLD.contato_id
     OR NEW.numero_registro IS DISTINCT FROM OLD.numero_registro
     OR NEW.versao IS DISTINCT FROM OLD.versao THEN
    RAISE EXCEPTION 'Propriedade e escopo do envio são imutáveis' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER envios_propriedade_imutavel
  BEFORE UPDATE OF escritorio_id, cliente_id, contato_id, numero_registro, versao ON envios_clientes
  FOR EACH ROW EXECUTE FUNCTION impedir_transferencia_envio();

CREATE FUNCTION impedir_mutacao_tentativa_envio() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Histórico de tentativa de envio é imutável' USING ERRCODE = '23514';
END;
$$;

CREATE TRIGGER tentativas_envio_sem_update_delete
  BEFORE UPDATE OR DELETE ON tentativas_envio
  FOR EACH ROW EXECUTE FUNCTION impedir_mutacao_tentativa_envio();
