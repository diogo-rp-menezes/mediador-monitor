-- Public-document extraction is platform work, never an office-owned decision.
CREATE TABLE tentativas_analise (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_registro text NOT NULL REFERENCES registros(numero_registro) ON DELETE RESTRICT,
  arquivo_hash text NOT NULL CHECK (arquivo_hash ~ '^[a-f0-9]{64}$'),
  config_versao bigint NOT NULL CHECK (config_versao > 0),
  modelo text NOT NULL,
  status_anterior text NOT NULL,
  inicio_anterior timestamptz,
  reserva_token uuid,
  status text NOT NULL CHECK (status IN ('executando','concluida','falhou')),
  motivo text,
  iniciada_em timestamptz NOT NULL DEFAULT now(),
  concluida_em timestamptz,
  CHECK ((status='executando' AND reserva_token IS NOT NULL AND concluida_em IS NULL AND motivo IS NULL)
      OR (status<>'executando' AND reserva_token IS NULL AND concluida_em IS NOT NULL))
);
CREATE UNIQUE INDEX tentativa_analise_ativa_uq ON tentativas_analise(numero_registro) WHERE status='executando';
ALTER TABLE tentativas_analise ENABLE ROW LEVEL SECURITY;
ALTER TABLE tentativas_analise FORCE ROW LEVEL SECURITY;
CREATE POLICY analise_plataforma ON tentativas_analise
  USING (mediador_contexto_global()) WITH CHECK (mediador_contexto_global());
CREATE FUNCTION proteger_tentativa_analise() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='DELETE' THEN
    RAISE EXCEPTION 'Histórico de análise não pode ser excluído' USING ERRCODE='23514';
  END IF;
  IF OLD.status<>'executando' OR NEW.status='executando'
    OR (NEW.id,NEW.numero_registro,NEW.arquivo_hash,NEW.config_versao,NEW.modelo,NEW.status_anterior,NEW.inicio_anterior,NEW.iniciada_em)
      IS DISTINCT FROM (OLD.id,OLD.numero_registro,OLD.arquivo_hash,OLD.config_versao,OLD.modelo,OLD.status_anterior,OLD.inicio_anterior,OLD.iniciada_em) THEN
    RAISE EXCEPTION 'Tentativa de análise é imutável após encerramento' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER tentativa_analise_protegida BEFORE UPDATE OR DELETE ON tentativas_analise
  FOR EACH ROW EXECUTE FUNCTION proteger_tentativa_analise();
