CREATE TABLE escritorios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  cnpj text,
  email text NOT NULL DEFAULT '',
  telefone text NOT NULL DEFAULT '',
  ativo boolean NOT NULL DEFAULT true,
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT escritorios_cnpj_normalizado UNIQUE (cnpj)
);

CREATE TABLE usuarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  email text NOT NULL,
  ativo boolean NOT NULL DEFAULT true,
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX usuarios_email_normalizado_uq ON usuarios(lower(email));

CREATE TABLE clientes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  razao_social text NOT NULL,
  nome_fantasia text NOT NULL DEFAULT '',
  cnpj text NOT NULL,
  uf text NOT NULL DEFAULT '',
  municipio text NOT NULL DEFAULT '',
  ativo boolean NOT NULL DEFAULT true,
  modo_envio text NOT NULL DEFAULT 'revisao' CHECK (modo_envio IN ('revisao','automatico')),
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  dados_cnpj_json jsonb,
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  CONSTRAINT clientes_cnpj_normalizado_uq UNIQUE (cnpj),
  CONSTRAINT clientes_id_escritorio_uq UNIQUE (id, escritorio_id)
);

CREATE INDEX clientes_escritorio_idx ON clientes(escritorio_id);

CREATE TABLE contatos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  email text NOT NULL,
  telefone text NOT NULL DEFAULT '',
  cargo text NOT NULL DEFAULT '',
  ativo boolean NOT NULL DEFAULT true,
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  CONSTRAINT contatos_id_escritorio_uq UNIQUE (id, escritorio_id)
);

CREATE INDEX contatos_escritorio_idx ON contatos(escritorio_id);
CREATE UNIQUE INDEX contatos_escritorio_email_uq ON contatos(escritorio_id, lower(email));

CREATE TABLE usuarios_escritorios (
  usuario_id integer NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  papel text NOT NULL CHECK (papel IN ('administrador','operador')),
  ativo boolean NOT NULL DEFAULT true,
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (usuario_id, escritorio_id)
);

CREATE INDEX usuarios_escritorio_idx ON usuarios_escritorios(escritorio_id, ativo);

CREATE TABLE usuarios_clientes (
  usuario_id integer NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  cliente_id integer NOT NULL,
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  ativo boolean NOT NULL DEFAULT true,
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (usuario_id, cliente_id),
  FOREIGN KEY (cliente_id, escritorio_id) REFERENCES clientes(id, escritorio_id) ON DELETE RESTRICT
);

CREATE INDEX usuarios_cliente_escritorio_idx ON usuarios_clientes(escritorio_id, ativo);

CREATE TABLE clientes_contatos (
  cliente_id integer NOT NULL,
  contato_id integer NOT NULL,
  escritorio_id integer NOT NULL,
  funcao text NOT NULL DEFAULT '',
  receber_email boolean NOT NULL DEFAULT true,
  tipos_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  PRIMARY KEY (cliente_id, contato_id),
  FOREIGN KEY (cliente_id, escritorio_id) REFERENCES clientes(id, escritorio_id) ON DELETE CASCADE,
  FOREIGN KEY (contato_id, escritorio_id) REFERENCES contatos(id, escritorio_id) ON DELETE RESTRICT
);

CREATE TABLE credenciais_usuarios (
  usuario_id integer PRIMARY KEY REFERENCES usuarios(id) ON DELETE RESTRICT,
  senha_hash text NOT NULL,
  atualizado_em bigint NOT NULL
);

CREATE TABLE papeis_plataforma (
  usuario_id integer PRIMARY KEY REFERENCES usuarios(id) ON DELETE RESTRICT,
  papel text NOT NULL CHECK (papel IN ('administrador_plataforma','suporte')),
  ativo boolean NOT NULL DEFAULT true
);

CREATE TABLE sessoes_usuarios (
  token_hash text PRIMARY KEY,
  usuario_id integer NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  criada_em bigint NOT NULL,
  ultimo_acesso_em bigint NOT NULL,
  expira_em bigint NOT NULL,
  revogada boolean NOT NULL DEFAULT false
);

CREATE INDEX sessoes_usuario_idx ON sessoes_usuarios(usuario_id, revogada, expira_em);

CREATE TABLE recuperacoes_acesso (
  token_hash text PRIMARY KEY,
  usuario_id integer NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  criada_em bigint NOT NULL,
  expira_em bigint NOT NULL,
  usada_em bigint
);

CREATE INDEX recuperacoes_usuario_idx ON recuperacoes_acesso(usuario_id, expira_em);

CREATE TABLE concessoes_suporte (
  id uuid PRIMARY KEY,
  sessao_hash text NOT NULL REFERENCES sessoes_usuarios(token_hash) ON DELETE RESTRICT,
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  justificativa text NOT NULL,
  criada_em bigint NOT NULL,
  expira_em bigint NOT NULL,
  revogada boolean NOT NULL DEFAULT false
);

CREATE INDEX concessoes_suporte_sessao_idx ON concessoes_suporte(sessao_hash, revogada, expira_em);

CREATE TABLE auditoria_seguranca (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ator_id integer REFERENCES usuarios(id) ON DELETE RESTRICT,
  acao text NOT NULL,
  escritorio_id integer REFERENCES escritorios(id) ON DELETE RESTRICT,
  cliente_id integer REFERENCES clientes(id) ON DELETE RESTRICT,
  criado_em bigint NOT NULL,
  ip text NOT NULL,
  user_agent text NOT NULL,
  request_id text NOT NULL,
  detalhes_json jsonb NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX auditoria_seguranca_ator_idx ON auditoria_seguranca(ator_id, criado_em);
CREATE INDEX auditoria_seguranca_escritorio_idx ON auditoria_seguranca(escritorio_id, id DESC);

