CREATE TABLE solicitacoes_analise (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero_registro text NOT NULL REFERENCES registros(numero_registro) ON DELETE RESTRICT,
  arquivo_hash text NOT NULL CHECK (arquivo_hash ~ '^[a-f0-9]{64}$'),
  solicitada_por integer REFERENCES usuarios(id) ON DELETE SET NULL,
  status text NOT NULL CHECK (status IN ('solicitada','executando','concluida','falhou')),
  tentativa_id integer REFERENCES tentativas_analise(id) ON DELETE RESTRICT,
  reserva_token uuid,
  motivo text,
  criada_em timestamptz NOT NULL DEFAULT now(),
  concluida_em timestamptz,
  CHECK ((status='solicitada' AND reserva_token IS NULL AND tentativa_id IS NULL AND concluida_em IS NULL)
    OR (status='executando' AND reserva_token IS NOT NULL AND concluida_em IS NULL)
    OR (status IN ('concluida','falhou') AND reserva_token IS NULL AND concluida_em IS NOT NULL))
);
CREATE UNIQUE INDEX solicitacao_analise_pendente_uq ON solicitacoes_analise(numero_registro) WHERE status IN ('solicitada','executando');
CREATE UNIQUE INDEX solicitacao_analise_tentativa_uq ON solicitacoes_analise(tentativa_id) WHERE tentativa_id IS NOT NULL;
ALTER TABLE solicitacoes_analise ENABLE ROW LEVEL SECURITY;
ALTER TABLE solicitacoes_analise FORCE ROW LEVEL SECURITY;
CREATE POLICY solicitacao_analise_plataforma ON solicitacoes_analise
  USING (mediador_contexto_global()) WITH CHECK (mediador_contexto_global());
