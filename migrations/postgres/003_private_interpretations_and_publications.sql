CREATE TABLE vinculos_escritorio (
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  aditivo text NOT NULL REFERENCES registros(numero_registro) ON DELETE RESTRICT,
  base text REFERENCES registros(numero_registro) ON DELETE RESTRICT,
  justificativa text NOT NULL,
  ator_id integer REFERENCES usuarios(id) ON DELETE RESTRICT,
  revisao integer NOT NULL DEFAULT 1 CHECK (revisao > 0),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (escritorio_id, aditivo)
);

CREATE INDEX vinculos_escritorio_base_idx ON vinculos_escritorio(escritorio_id, base);

CREATE TABLE interpretacoes_escritorio (
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  base text NOT NULL REFERENCES registros(numero_registro) ON DELETE RESTRICT,
  entrada_hash text NOT NULL,
  resultado_json jsonb NOT NULL,
  revisoes_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  versao text NOT NULL,
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (escritorio_id, base)
);

CREATE TABLE versoes_interpretacao (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  base text NOT NULL REFERENCES registros(numero_registro) ON DELETE RESTRICT,
  versao text NOT NULL,
  resultado_json jsonb NOT NULL,
  ator_id integer REFERENCES usuarios(id) ON DELETE RESTRICT,
  criado_em timestamptz NOT NULL DEFAULT now(),
  UNIQUE(escritorio_id, base, versao)
);

CREATE TABLE historico_interpretacoes_legado (
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  entidade text NOT NULL,
  conteudo_json jsonb NOT NULL
);

CREATE TABLE publicacoes_documentos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  escritorio_id integer NOT NULL,
  cliente_id integer NOT NULL,
  base text NOT NULL REFERENCES registros(numero_registro) ON DELETE RESTRICT,
  versao text NOT NULL,
  hash_pdf text NOT NULL,
  relatorio_json jsonb NOT NULL,
  pdf bytea NOT NULL,
  ator_id integer NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  estado text NOT NULL DEFAULT 'ativa' CHECK (estado IN ('ativa','revogada')),
  criada_em timestamptz NOT NULL DEFAULT now(),
  revogada_em timestamptz,
  UNIQUE(escritorio_id, cliente_id, base, versao),
  FOREIGN KEY(cliente_id, escritorio_id) REFERENCES clientes(id, escritorio_id) ON DELETE RESTRICT
);

CREATE INDEX publicacoes_cliente_idx ON publicacoes_documentos(escritorio_id, cliente_id, estado, id DESC);

CREATE FUNCTION impedir_alteracao_propriedade_publicacao() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.escritorio_id IS DISTINCT FROM OLD.escritorio_id
     OR NEW.cliente_id IS DISTINCT FROM OLD.cliente_id
     OR NEW.base IS DISTINCT FROM OLD.base
     OR NEW.versao IS DISTINCT FROM OLD.versao THEN
    RAISE EXCEPTION 'Propriedade e versão da publicação são imutáveis' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER publicacoes_propriedade_imutavel
  BEFORE UPDATE OF escritorio_id, cliente_id, base, versao ON publicacoes_documentos
  FOR EACH ROW EXECUTE FUNCTION impedir_alteracao_propriedade_publicacao();

CREATE TABLE auditoria_acessos_publicacoes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  cliente_id integer NOT NULL REFERENCES clientes(id) ON DELETE RESTRICT,
  publicacao_id bigint REFERENCES publicacoes_documentos(id) ON DELETE RESTRICT,
  versao text NOT NULL,
  ator_id integer REFERENCES usuarios(id) ON DELETE SET NULL,
  evento text NOT NULL CHECK (evento IN ('publicada','revogada','abertura_autorizada','download_servido','ciencia_confirmada','acesso_negado')),
  resultado text NOT NULL,
  criado_em timestamptz NOT NULL DEFAULT now(),
  ip text NOT NULL DEFAULT '',
  user_agent text NOT NULL DEFAULT '',
  request_id text NOT NULL DEFAULT '',
  FOREIGN KEY(cliente_id, escritorio_id) REFERENCES clientes(id, escritorio_id) ON DELETE RESTRICT
);

CREATE INDEX auditoria_publicacoes_idx ON auditoria_acessos_publicacoes(escritorio_id, id DESC);

CREATE FUNCTION impedir_mutacao_auditoria_publicacao() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Auditoria de publicação é imutável' USING ERRCODE = '23514';
END;
$$;

CREATE TRIGGER auditoria_publicacoes_sem_update
  BEFORE UPDATE OR DELETE ON auditoria_acessos_publicacoes
  FOR EACH ROW EXECUTE FUNCTION impedir_mutacao_auditoria_publicacao();

CREATE TABLE notificacoes_publicacoes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  publicacao_id bigint NOT NULL REFERENCES publicacoes_documentos(id) ON DELETE RESTRICT,
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  cliente_id integer NOT NULL REFERENCES clientes(id) ON DELETE RESTRICT,
  usuario_id integer NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
  destino text NOT NULL,
  estado text NOT NULL DEFAULT 'pendente' CHECK (estado IN ('pendente','enviando','enviado','falhou','incerto','cancelado')),
  tentativas integer NOT NULL DEFAULT 0 CHECK (tentativas >= 0),
  erro text,
  criada_em timestamptz NOT NULL DEFAULT now(),
  enviada_em timestamptz,
  UNIQUE(publicacao_id, destino),
  FOREIGN KEY(cliente_id, escritorio_id) REFERENCES clientes(id, escritorio_id) ON DELETE RESTRICT
);

CREATE INDEX notificacoes_publicacao_estado_idx ON notificacoes_publicacoes(escritorio_id, estado, id);

CREATE FUNCTION impedir_transferencia_interpretacao() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.escritorio_id IS DISTINCT FROM OLD.escritorio_id THEN
    RAISE EXCEPTION 'Propriedade da interpretação é imutável' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER vinculos_escritorio_proprietario_imutavel
  BEFORE UPDATE OF escritorio_id ON vinculos_escritorio
  FOR EACH ROW EXECUTE FUNCTION impedir_transferencia_interpretacao();
CREATE TRIGGER interpretacoes_escritorio_proprietario_imutavel
  BEFORE UPDATE OF escritorio_id ON interpretacoes_escritorio
  FOR EACH ROW EXECUTE FUNCTION impedir_transferencia_interpretacao();
CREATE TRIGGER versoes_interpretacao_proprietario_imutavel
  BEFORE UPDATE OF escritorio_id ON versoes_interpretacao
  FOR EACH ROW EXECUTE FUNCTION impedir_transferencia_interpretacao();
