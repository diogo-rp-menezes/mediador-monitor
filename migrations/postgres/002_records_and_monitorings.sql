CREATE TABLE registros (
  numero_registro text PRIMARY KEY,
  numero_solicitacao text,
  watch text NOT NULL,
  tipo text,
  vigencia text,
  partes text,
  arquivo_path text,
  arquivo_hash text,
  arquivo_tamanho integer,
  arquivo_nome text,
  download_erro text,
  extracao_json jsonb,
  analise_status text NOT NULL DEFAULT 'sem_analise',
  analise_erro text,
  analise_iniciada_em timestamptz,
  analise_concluida_em timestamptz,
  primeira_vez timestamptz NOT NULL DEFAULT now(),
  notificado boolean NOT NULL DEFAULT false,
  documento_meta_json jsonb
);

CREATE INDEX registros_arquivo_hash_idx ON registros(arquivo_hash);
CREATE INDEX registros_watch_idx ON registros(watch);

CREATE TABLE sindicatos (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  cnpj text NOT NULL DEFAULT '',
  categoria text NOT NULL DEFAULT '',
  uf text NOT NULL DEFAULT '',
  tipo text NOT NULL DEFAULT '',
  tipos_json jsonb NOT NULL DEFAULT '[]'::jsonb,
  vigencia text NOT NULL DEFAULT '',
  titulo text NOT NULL DEFAULT '',
  ativo boolean NOT NULL DEFAULT true,
  criado_em timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX sindicatos_nome_idx ON sindicatos(lower(nome), id);

CREATE TABLE clientes_sindicatos (
  cliente_id integer NOT NULL REFERENCES clientes(id) ON DELETE CASCADE,
  sindicato_id integer NOT NULL REFERENCES sindicatos(id) ON DELETE RESTRICT,
  categoria text NOT NULL DEFAULT '',
  uf text NOT NULL DEFAULT '',
  municipio text NOT NULL DEFAULT '',
  principal boolean NOT NULL DEFAULT false,
  enquadramento_confirmado boolean NOT NULL DEFAULT false,
  PRIMARY KEY(cliente_id, sindicato_id)
);

CREATE UNIQUE INDEX cliente_sindicato_principal_uq ON clientes_sindicatos(cliente_id) WHERE principal;
CREATE INDEX clientes_sindicatos_sindicato_idx ON clientes_sindicatos(sindicato_id);

CREATE TABLE registros_sindicatos (
  numero_registro text NOT NULL REFERENCES registros(numero_registro) ON DELETE CASCADE,
  sindicato_id integer NOT NULL REFERENCES sindicatos(id) ON DELETE RESTRICT,
  PRIMARY KEY(numero_registro, sindicato_id)
);

CREATE INDEX registros_sindicatos_sindicato_idx ON registros_sindicatos(sindicato_id);

CREATE TABLE monitoramentos_escritorios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  sindicato_id integer NOT NULL REFERENCES sindicatos(id) ON DELETE RESTRICT,
  nome text NOT NULL,
  cnpj_filtro text NOT NULL DEFAULT '',
  categoria text NOT NULL DEFAULT '',
  uf text NOT NULL DEFAULT '',
  tipos_json jsonb NOT NULL,
  vigencia text NOT NULL DEFAULT '',
  titulo text NOT NULL DEFAULT '',
  ativo boolean NOT NULL DEFAULT true,
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  UNIQUE(escritorio_id, sindicato_id)
);

CREATE INDEX monitoramentos_escritorio_idx ON monitoramentos_escritorios(escritorio_id, lower(nome), id);

CREATE FUNCTION impedir_transferencia_monitoramento() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.escritorio_id IS DISTINCT FROM OLD.escritorio_id OR NEW.sindicato_id IS DISTINCT FROM OLD.sindicato_id THEN
    RAISE EXCEPTION 'Propriedade do monitoramento é imutável' USING ERRCODE = '23514';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER monitoramentos_propriedade_imutavel
  BEFORE UPDATE OF escritorio_id, sindicato_id ON monitoramentos_escritorios
  FOR EACH ROW EXECUTE FUNCTION impedir_transferencia_monitoramento();

CREATE TABLE execucoes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  iniciada_em timestamptz NOT NULL DEFAULT now(),
  watch text,
  tipo_instrumento text NOT NULL DEFAULT '',
  encontrados integer,
  novos integer,
  erro text
);

CREATE INDEX execucoes_data_idx ON execucoes(iniciada_em DESC);

CREATE TABLE execucoes_escritorio (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  escritorio_id integer NOT NULL REFERENCES escritorios(id) ON DELETE RESTRICT,
  solicitada_por integer REFERENCES usuarios(id) ON DELETE SET NULL,
  status text NOT NULL CHECK (status IN ('solicitada','executando','concluida','falhou','cancelada')),
  detalhes_json jsonb NOT NULL DEFAULT '{}'::jsonb,
  iniciada_em timestamptz NOT NULL DEFAULT now(),
  concluida_em timestamptz
);

CREATE INDEX execucoes_escritorio_data_idx ON execucoes_escritorio(escritorio_id, id DESC);
